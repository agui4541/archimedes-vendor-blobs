#!/usr/bin/env python3
"""Generate the vendor makefiles from proprietary-files.txt."""
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
rows=[]
for raw in (ROOT/'proprietary-files.txt').read_text(encoding='utf-8').splitlines():
    line=raw.strip()
    if not line or line.startswith('#'): continue
    parts=line.split(':')
    if len(parts) not in (2,3): raise SystemExit(f'bad manifest line: {raw}')
    source,path=parts[:2]
    dest=parts[2] if len(parts)==3 else path
    rows.append((source,path,dest))
lines=['# Generated by scripts/setup-makefiles.sh.','', 'PRODUCT_COPY_FILES += \\']
if rows:
    for i,(source,path,dest) in enumerate(rows):
        suffix=' \\' if i < len(rows)-1 else ''
        lines.append(f'    vendor/xiaomi/archimedes/proprietary/{dest}:$(TARGET_COPY_OUT_{source.upper()})/{dest}{suffix}')
else:
    lines.append('    # No reviewed proprietary files have been imported yet.')
(ROOT/'archimedes-vendor.mk').write_text('\n'.join(lines)+'\n',encoding='utf-8')
print(f'generated makefile for {len(rows)} files')
